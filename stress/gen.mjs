// Stress projects for blueprint42, at any size: the Tests menu builds them
// in the page, and node writes them as folders for stress/bench.mjs.
//
//   node stress/gen.mjs [N ...] [--out DIR]   (default N = 256 1024,
//                                             DIR = $TMPDIR/blueprint42-stress)
//
// Every project keeps the Norm's shape: at most 25 lines and 4 parameters
// per function, 5 variables, 5 functions per file, declarations first, no
// for / ternary / switch (norminette finds nothing but the missing 42
// header). Cases:
//   pointers   N heap nodes in a linked list, walked by an N-deep recursion
//              whose every frame holds a pointer (N pointer lines at once)
//   files      N functions across N/5 files, each calling the next
//   struct     one struct of N fields, filled by N/20 setters, passed by value
//   pushswap   push_swap: N numbers sorted by radix with two stacks, every op
//              written out (a very long run, and a lot of output)
//   heap       N malloc'd strings, half freed, one leaked
//   output     N lines of printf mixed with write (printf's buffer vs write)

const HDR = '/* generated by stress/gen.mjs for blueprint42 */\n';

const makefile = (name, srcs) => `NAME = ${name}
SRCS = ${srcs.join(' ')}
OBJS = $(SRCS:.c=.o)
CFLAGS = -Wall -Wextra -Werror

all: $(NAME)

$(NAME): $(OBJS)
	$(CC) $(CFLAGS) $(OBJS) -o $(NAME)

%.o: %.c
	$(CC) $(CFLAGS) -c $< -o $@

clean:
	rm -f $(OBJS)

fclean: clean
	rm -f $(NAME)

re: fclean all

.PHONY: all clean fclean re
`;

const guard = (name, body) => {
  const g = name.toUpperCase().replace('.', '_');
  return `#ifndef ${g}\n# define ${g}\n\n${body}\n#endif\n`;
};

function pointers(n) {
  const h = guard('plist.h', `# include <stdlib.h>
# include <stdio.h>

# define LIST_N ${n}

typedef struct s_node
{
	int				value;
	struct s_node	*next;
}	t_node;

t_node	*node_new(int value);
t_node	*list_build(int n);
long	list_walk(t_node *node, int depth);
void	list_free(t_node *node);
`);
  const c = `#include "plist.h"

t_node	*node_new(int value)
{
	t_node	*node;

	node = malloc(sizeof(t_node));
	if (!node)
		return (NULL);
	node->value = value;
	node->next = NULL;
	return (node);
}

t_node	*list_build(int n)
{
	t_node	*head;
	t_node	*node;

	head = NULL;
	while (n > 0)
	{
		node = node_new(n);
		if (!node)
			return (head);
		node->next = head;
		head = node;
		n--;
	}
	return (head);
}

long	list_walk(t_node *node, int depth)
{
	if (!node)
		return (0);
	return (node->value + list_walk(node->next, depth + 1));
}

void	list_free(t_node *node)
{
	t_node	*next;

	while (node)
	{
		next = node->next;
		free(node);
		node = next;
	}
}
`;
  const m = `#include "plist.h"

int	main(void)
{
	t_node	*head;
	long	sum;

	head = list_build(LIST_N);
	sum = list_walk(head, 0);
	printf("sum %ld\\n", sum);
	list_free(head);
	return (0);
}
`;
  return { 'plist.h': h, 'plist.c': c, 'main.c': m };
}

function files(n) {
  const out = {};
  const protos = [];
  for (let k = 0; k < n; k += 5) {
    const body = ['#include "chain.h"\n'];
    for (let i = k; i < Math.min(k + 5, n); i++) {
      protos.push(`int\tf_${i}(int x);`);
      const nxt = i + 1 < n ? `f_${i + 1}(x + 1)` : 'x';
      body.push(`int\tf_${i}(int x)\n{\n\treturn (${nxt});\n}\n`);
    }
    out[`chain_${String(k / 5).padStart(3, '0')}.c`] = body.join('\n');
  }
  out['chain.h'] = guard('chain.h', '# include <stdio.h>\n\n' + protos.join('\n') + '\n');
  out['main.c'] = `#include "chain.h"

int	main(void)
{
	printf("%d\\n", f_0(0));
	return (0);
}
`;
  return out;
}

function struct(n) {
  const fields = Array.from({ length: n }, (_, i) => `\tint\tf${i};`).join('\n');
  const setters = Math.ceil(n / 20);
  const protos = Array.from({ length: setters }, (_, k) => `void\tset_${k}(t_big *b);`).join('\n');
  const out = {
    'big.h': guard('big.h', `# include <stdlib.h>
# include <stdio.h>

typedef struct s_big
{
${fields}
}\tt_big;

${protos}
long\tbig_sum(t_big b);
`),
  };
  for (let k = 0; k < setters; k += 5) {
    const body = ['#include "big.h"\n'];
    for (let s = k; s < Math.min(k + 5, setters); s++) {
      const lines = [];
      for (let i = s * 20; i < Math.min(s * 20 + 20, n); i++) lines.push(`\tb->f${i} = ${i};`);
      body.push(`void\tset_${s}(t_big *b)\n{\n${lines.join('\n')}\n}\n`);
    }
    out[`set_${String(k / 5).padStart(3, '0')}.c`] = body.join('\n');
  }
  out['sum.c'] = `#include "big.h"

long\tbig_sum(t_big b)
{
\treturn ((long)b.f0 + b.f${n - 1});
}
`;
  // main can't hold every setter call within 25 lines: fill_ helpers of 20
  const calls = Array.from({ length: setters }, (_, k) => `\tset_${k}(b);`);
  const run = [];
  for (let i = 0, j = 0; i < setters; i += 20, j++) run.push(`static void\tfill_${j}(t_big *b)\n{\n${calls.slice(i, i + 20).join('\n')}\n}\n`);
  const fills = run.map((_, j) => `\tfill_${j}(b);`).join('\n');
  // main.c holds at most 4 fill_ helpers plus main (5 functions); more go in fill files
  const inMain = run.slice(0, 4);
  const extra = run.slice(4);
  for (let j = 0; j < extra.length; j += 5) {
    out[`fill_${String(j / 5).padStart(3, '0')}.c`] = '#include "big.h"\n\n' + extra.slice(j, j + 5).map((x) => x.replace('static void', 'void')).join('\n');
  }
  if (extra.length) out['big.h'] = out['big.h'].replace('long\tbig_sum', extra.map((_, j) => `void\tfill_${j + 4}(t_big *b);`).join('\n') + '\nlong\tbig_sum');
  out['main.c'] = '#include "big.h"\n\n' + inMain.join('\n') + `
int\tmain(void)
{
\tt_big\t*b;

\tb = malloc(sizeof(t_big));
\tif (!b)
\t\treturn (1);
${fills}
\tprintf("%ld\\n", big_sum(*b));
\tfree(b);
\treturn (0);
}
`;
  return out;
}

function pushswap(n) {
  const h = guard('push_swap.h', `# include <unistd.h>

# define STACK_N ${n}

typedef struct s_stacks
{
	int	a[STACK_N];
	int	b[STACK_N];
	int	na;
	int	nb;
}	t_stacks;

void	op_pb(t_stacks *s);
void	op_pa(t_stacks *s);
void	op_ra(t_stacks *s);
void	fill_ranks(t_stacks *s, unsigned int seed);
void	radix_sort(t_stacks *s);
`);
  const ops = `#include "push_swap.h"

static void	shift_down(int *st, int n)
{
	while (n > 0)
	{
		st[n] = st[n - 1];
		n--;
	}
}

static void	shift_up(int *st, int n)
{
	int	i;

	i = 0;
	while (i + 1 < n)
	{
		st[i] = st[i + 1];
		i++;
	}
}

void	op_pb(t_stacks *s)
{
	shift_down(s->b, s->nb);
	s->b[0] = s->a[0];
	shift_up(s->a, s->na);
	s->na--;
	s->nb++;
	write(1, "pb\\n", 3);
}

void	op_pa(t_stacks *s)
{
	shift_down(s->a, s->na);
	s->a[0] = s->b[0];
	shift_up(s->b, s->nb);
	s->nb--;
	s->na++;
	write(1, "pa\\n", 3);
}

void	op_ra(t_stacks *s)
{
	int	first;

	first = s->a[0];
	shift_up(s->a, s->na);
	s->a[s->na - 1] = first;
	write(1, "ra\\n", 3);
}
`;
  const sort = `#include "push_swap.h"

static unsigned int	next_rand(unsigned int seed)
{
	return (seed * 1103515245u + 12345u);
}

static int	rank_of(int *raw, int n, int i)
{
	int	j;
	int	rank;

	j = 0;
	rank = 0;
	while (j < n)
	{
		if (raw[j] < raw[i])
			rank++;
		j++;
	}
	return (rank);
}

void	fill_ranks(t_stacks *s, unsigned int seed)
{
	int	i;

	i = 0;
	while (i < STACK_N)
	{
		seed = next_rand(seed);
		s->b[i] = (int)(seed >> 8) + i;
		i++;
	}
	i = 0;
	while (i < STACK_N)
	{
		s->a[i] = rank_of(s->b, STACK_N, i);
		i++;
	}
	s->na = STACK_N;
	s->nb = 0;
}

static void	radix_pass(t_stacks *s, int bit)
{
	int	count;

	count = s->na;
	while (count > 0)
	{
		if ((s->a[0] >> bit) & 1)
			op_ra(s);
		else
			op_pb(s);
		count--;
	}
	while (s->nb > 0)
		op_pa(s);
}

void	radix_sort(t_stacks *s)
{
	int	bit;

	bit = 0;
	while ((STACK_N - 1) >> bit)
	{
		radix_pass(s, bit);
		bit++;
	}
}
`;
  const m = `#include "push_swap.h"
#include <stdlib.h>

int	main(void)
{
	t_stacks	*s;

	s = malloc(sizeof(t_stacks));
	if (!s)
		return (1);
	fill_ranks(s, 42);
	radix_sort(s);
	free(s);
	return (0);
}
`;
  return { 'push_swap.h': h, 'ops.c': ops, 'sort.c': sort, 'main.c': m };
}

function heap(n) {
  const h = guard('strs.h', `# include <stdlib.h>
# include <stdio.h>

# define STR_N ${n}

char	*str_make(int i);
void	free_half(char **strs, int n);
`);
  const c = `#include "strs.h"

char	*str_make(int i)
{
	char	*s;
	int		len;

	len = 4 + i % 12;
	s = malloc(len + 1);
	if (!s)
		return (NULL);
	s[len] = '\\0';
	while (len > 0)
	{
		len--;
		s[len] = 'a' + (i + len) % 26;
	}
	return (s);
}

void	free_half(char **strs, int n)
{
	int	i;

	i = 0;
	while (i < n)
	{
		free(strs[i]);
		strs[i] = NULL;
		i += 2;
	}
}
`;
  const m = `#include "strs.h"

int	main(void)
{
	char	**strs;
	int		i;

	strs = malloc(sizeof(char *) * STR_N);
	if (!strs)
		return (1);
	i = 0;
	while (i < STR_N)
	{
		strs[i] = str_make(i);
		i++;
	}
	free_half(strs, STR_N);
	i = 1;
	while (i < STR_N - 2)
	{
		free(strs[i]);
		i += 2;
	}
	printf("kept %s\\n", strs[STR_N - 1]);
	free(strs);
	return (0);
}
`;
  return { 'strs.h': h, 'strs.c': c, 'main.c': m };
}

function output(n) {
  return {
    'main.c': `#include <stdio.h>
#include <unistd.h>

#define LINES_N ${n}

int\tmain(void)
{
\tint\ti;

\ti = 0;
\twhile (i < LINES_N)
\t{
\t\tprintf("line %d", i);
\t\tif (i % 10 == 0)
\t\t\twrite(1, " [write]", 8);
\t\tprintf("\\n");
\t\ti++;
\t}
\treturn (0);
}
`,
  };
}

export const STRESS_SIZES = [256, 1024];

export const STRESS_CASES = [
  { id: 'pointers', title: 'pointers', blurb: 'a linked list of N heap nodes, walked by an N-deep recursion: N pointer lines at once', make: pointers },
  { id: 'files', title: 'files', blurb: 'N functions, five to a file, each calling the next', make: files },
  { id: 'struct', title: 'huge struct', blurb: 'one struct of N fields, filled by setters and passed by value', make: struct },
  { id: 'pushswap', title: 'push_swap', blurb: 'N numbers radix-sorted with two stacks, every op written: a very long run', make: pushswap },
  { id: 'heap', title: 'heap', blurb: 'N malloc’d strings, half freed, one leaked', make: heap },
  { id: 'output', title: 'output', blurb: 'N lines of printf mixed with write: printf’s buffer against write', make: output },
];

// A case's files at size n, with its Makefile (each file keeps the header line).
export function stressFiles(id, n) {
  const c = STRESS_CASES.find((x) => x.id === id);
  if (!c) throw new Error(`no stress case ${id}`);
  const made = c.make(n);
  const out = {};
  for (const [path, text] of Object.entries(made)) out[path] = HDR + text;
  out.Makefile = makefile(id, Object.keys(made).filter((p) => p.endsWith('.c')).sort());
  return out;
}

// node stress/gen.mjs: write every case as a folder
if (typeof process !== 'undefined' && process.argv[1] && import.meta.url === (await import('node:url')).pathToFileURL(process.argv[1]).href) {
  const { mkdir, writeFile } = await import('node:fs/promises');
  const { join } = await import('node:path');
  const { tmpdir } = await import('node:os');
  const args = process.argv.slice(2);
  let outDir = join(tmpdir(), 'blueprint42-stress');
  const sizes = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--out') outDir = args[++i];
    else sizes.push(Number(args[i]));
  }
  for (const n of sizes.length ? sizes : STRESS_SIZES) {
    for (const c of STRESS_CASES) {
      const root = join(outDir, `${c.id}-${n}`);
      await mkdir(root, { recursive: true });
      for (const [path, text] of Object.entries(stressFiles(c.id, n))) await writeFile(join(root, path), text);
      console.log(root);
    }
  }
}
