// How heavy each skin is (docs/OBJECTIVES.md, nice to have 12): bench
// results (tools/bench.mjs --uncapped --save) written as src/skins/weight-data.ts,
// which the skin picker reads. Per skin, the median over rounds of: a frame's
// whole cost (1000 / uncapped fps: CPU and GPU), the grid's CPU paint time,
// and the canvas gradients a frame makes (Firefox pays more for those).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO } from './serve.mjs';

const med = (xs) => { const s = [...xs].sort((a, b) => a - b); return s[s.length >> 1]; };
const r2 = (x) => Math.round(x * 100) / 100;

export function saveWeights(results, how) {
  const skins = {};
  for (const id of [...new Set(results.map((r) => r.skin))]) {
    const rs = results.filter((r) => r.skin === id && r.fps > 0);
    if (!rs.length) continue;
    const cpu = (r) => Object.values(r.report?.passMs ?? {}).reduce((a, b) => a + b, 0);
    const grad = (r) => (r.report?.canvasCalls?.createLinearGradient ?? 0) + (r.report?.canvasCalls?.createRadialGradient ?? 0);
    skins[id] = { ms: r2(med(rs.map((r) => 1000 / r.fps))), cpu: r2(med(rs.map(cpu))), grad: Math.round(med(rs.map(grad))) };
  }
  const file = join(REPO, 'src/skins/weight-data.ts');
  writeFileSync(file, `// Generated by \`node tools/bench.mjs --uncapped --save\` (tools/lib/weights.mjs): edit by running it again.
// ms: a frame's whole cost (1000 / uncapped fps), cpu: the grid's paint (ms), grad: canvas gradients a frame.
export const WEIGHT_MEASURED = ${JSON.stringify({ when: new Date().toISOString().slice(0, 10), ...how })};
export const WEIGHTS: Record<string, { ms: number; cpu: number; grad: number }> = ${JSON.stringify(skins, null, 2)};
`);
  return file;
}
